-- Resultado de cada aplicacao do teste vocacional (1a regra de negocio).
CREATE TABLE vocational_test_result (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at          TIMESTAMP(6) NOT NULL,
    realistic_score     INTEGER      NOT NULL,
    investigative_score INTEGER      NOT NULL,
    artistic_score      INTEGER      NOT NULL,
    social_score        INTEGER      NOT NULL,
    enterprising_score  INTEGER      NOT NULL,
    conventional_score  INTEGER      NOT NULL,
    top_categories      VARCHAR(100) NOT NULL,
    recommended_areas   VARCHAR(500) NOT NULL
);
