-- Formas de ingresso no ensino superior exibidas na pagina inicial publica (RF01)
-- e gerenciadas pelo administrador (RF11). Nao ha exclusao fisica: o registro e desativado.
CREATE TABLE admission_method (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100)  NOT NULL UNIQUE,
    type          VARCHAR(30)   NOT NULL,
    summary       VARCHAR(300)  NOT NULL,
    description   VARCHAR(1000) NOT NULL,
    how_it_works  VARCHAR(1500) NOT NULL,
    eligibility   VARCHAR(1000) NOT NULL,
    schedule      VARCHAR(500)  NOT NULL,
    cost          VARCHAR(500)  NOT NULL,
    tips          VARCHAR(1000),
    official_url  VARCHAR(300)  NOT NULL,
    active        BOOLEAN       NOT NULL,
    display_order INT           NOT NULL,
    updated_at    TIMESTAMP(6)  NOT NULL
);
CREATE INDEX idx_admission_method_active ON admission_method (active);

