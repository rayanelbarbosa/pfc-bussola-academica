-- Recuperacao de senha: token de uso unico com validade curta. So o hash SHA-256 do token fica no banco,
-- entao quem tiver acesso ao banco nao consegue usar um link de redefinicao.
CREATE TABLE password_reset_token (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    token_hash VARCHAR(64)  NOT NULL UNIQUE,
    created_at TIMESTAMP(6) NOT NULL,
    expires_at TIMESTAMP(6) NOT NULL,
    used_at    TIMESTAMP(6)
);
CREATE INDEX idx_password_reset_token_user ON password_reset_token (user_id);

-- Data da ultima troca de senha: tokens JWT emitidos antes dela deixam de valer (encerra as sessoes abertas).
ALTER TABLE app_user ADD COLUMN password_changed_at TIMESTAMP(6);
